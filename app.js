function bindFormExtras(type, row) {
  const form = document.getElementById("entry-form");
  form.querySelector("#form-cancel").addEventListener("click", closeDialog);
  const stornoBtn = form.querySelector("#form-storno");
  if (stornoBtn) stornoBtn.addEventListener("click", () => toggleStorno(type, row.id, true));
  const unstornoBtn = form.querySelector("#form-unstorno");
  if (unstornoBtn) unstornoBtn.addEventListener("click", () => toggleStorno(type, row.id, false));
  if (type === "invoice") {
    const inputEl = form.querySelector("#photo-input");
    const preview = form.querySelector("#photo-preview");
    const remove = form.querySelector("#photo-remove");
    inputEl.addEventListener("change", () => {
      const file = inputEl.files && inputEl.files[0];
      if (!file) return;
      const reader = new FileReader();
      reader.onload = () => {
        state.pendingImage = reader.result;
        preview.src = reader.result;
        preview.hidden = false;
      };
      reader.readAsDataURL(file);
    });
    remove.addEventListener("click", () => {
      state.pendingImage = null;
      preview.removeAttribute("src");
      preview.hidden = true;
      inputEl.value = "";
    });
  }
}

async function toggleStorno(type, id, flag) {
  if (flag && !confirm(t("stornoConfirm"))) return;
  const store = storeName(type);
  const record = state.data[store].find((row) => row.id === id);
  if (!record) return;
  record.storno = flag;
  record.updated = todayIso();
  await putRecord(store, record);
  await loadAll();
  closeDialog();
  render();
}

function formData(form) {
  const data = {};
  new FormData(form).forEach((value, key) => {
    data[key] = typeof value === "string" ? value.trim() : value;
  });
  return data;
}

function numOrEmpty(value) {
  if (value === "" || value == null) return "";
  const n = Number(String(value).replace(",", "."));
  return Number.isNaN(n) ? "" : n;
}

async function saveForm(event) {
  event.preventDefault();
  const form = event.target;
  if (!form.reportValidity()) {
    alert(t("required"));
    return;
  }
  const type = state.editing.type;
  const raw = formData(form);
  const id = state.editing.id || uid();
  const existing = state.editing.id ? state.data[storeName(type)].find((row) => row.id === id) || {} : {};
  let record;

  if (type === "invoice") {
    record = {
      ...existing,
      id,
      kind: raw.kind === "out" ? "out" : "in",
      date: raw.date,
      number: raw.number,
      partner: raw.partner,
      net: numOrEmpty(raw.net),
      gross: numOrEmpty(raw.gross),
      description: raw.description || "",
      paid: raw.paid === "1",
      image: state.pendingImage || "",
      storno: existing.storno || false
    };
    if (record.net === "" && record.gross === "") {
      alert(t("required"));
      return;
    }
    await rememberSupplier(record.partner);
  } else if (type === "order") {
    record = {
      ...existing,
      id,
      date: raw.date,
      supplier: raw.supplier,
      part: raw.part,
      qty: numOrEmpty(raw.qty),
      price: numOrEmpty(raw.price),
      status: raw.status || "open",
      note: raw.note || "",
      storno: existing.storno || false
    };
    await rememberSupplier(record.supplier);
  } else if (type === "return") {
    const amount = Math.abs(Number(numOrEmpty(raw.amount) || 0));
    const order = state.data.orders.find((item) => item.id === raw.orderId);
    record = {
      ...existing,
      id,
      date: raw.date,
      orderId: raw.orderId,
      supplier: order ? order.supplier : existing.supplier || "",
      amount: amount ? -amount : 0,
      note: raw.note || "",
      storno: existing.storno || false
    };
  } else if (type === "movement") {
    record = {
      ...existing,
      id,
      date: raw.date,
      dir: raw.dir === "out" ? "out" : "in",
      item: raw.item,
      qty: numOrEmpty(raw.qty),
      partner: raw.partner || "",
      ref: raw.ref || "",
      note: raw.note || "",
      storno: existing.storno || false
    };
    if (record.partner) await rememberSupplier(record.partner);
  } else {
    record = {
      ...existing,
      id,
      name: raw.name,
      city: raw.city || "",
      contact: raw.contact || "",
      note: raw.note || "",
      storno: existing.storno || false
    };
  }

  record.updated = todayIso();
  if (!existing.id) record.created = todayIso();
  await putRecord(storeName(type), record);
  await loadAll();
  closeDialog();
  render();
}


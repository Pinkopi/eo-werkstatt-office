function optionList(values, selected, emptyLabel) {
  return (
    (emptyLabel ? `<option value="">${emptyLabel}</option>` : "") +
    values
      .map((value) => {
        const isObj = typeof value === "object";
        const val = isObj ? value.value : value;
        const label = isObj ? value.label : value;
        return `<option value="${escapeAttr(val)}" ${String(val) === String(selected) ? "selected" : ""}>${escapeHtml(label)}</option>`;
      })
      .join("")
  );
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function escapeAttr(value) {
  return escapeHtml(value);
}

function field(label, control, span) {
  return `<label class="field-label${span ? " span-2" : ""}"><span>${label}</span>${control}</label>`;
}

function input(name, type, value, required, extra) {
  const req = required ? "required" : "";
  return `<input name="${name}" type="${type}" value="${escapeAttr(value ?? "")}" ${req} ${extra || ""}>`;
}

function closeDialog() {
  const dialog = document.getElementById("form-dialog");
  dialog.close();
  state.editing = null;
  state.pendingImage = null;
  document.getElementById("entry-form").innerHTML = "";
}

function openForm(type, id) {
  const record = id ? state.data[storeName(type)].find((row) => row.id === id) : null;
  if (type === "return" && !record && state.data.orders.filter((row) => !row.storno).length === 0) {
    alert(t("returnNeedOrder"));
    return;
  }
  state.editing = { type, id: record ? record.id : null };
  state.pendingImage = record && record.image ? record.image : null;
  document.getElementById("form-title").textContent = t(
    record
      ? { invoice: "editInvoice", order: "editOrder", return: "editReturn", movement: "editMovement", supplier: "editSupplier" }[type]
      : { invoice: "addInvoice", order: "addOrder", return: "addReturn", movement: "addMovement", supplier: "addSupplier" }[type]
  );
  document.getElementById("form-hint").textContent = type === "invoice" ? t("fPhotoHint") : "";
  document.getElementById("entry-form").innerHTML = formHtml(type, record || {});
  bindFormExtras(type, record || {});
  const dialog = document.getElementById("form-dialog");
  if (!dialog.open) dialog.showModal();
}

function storeName(type) {
  return { invoice: "invoices", order: "orders", return: "returns", movement: "movements", supplier: "suppliers" }[type];
}

function supplierNames() {
  return state.data.suppliers.filter((row) => !row.storno).map((row) => row.name);
}


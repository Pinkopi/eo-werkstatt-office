function exportExcel() {
  const k = kpis();
  const kpiRows = [
    { Kennzahl: "Umsatz / Promet", Wert: k.revenue, Hinweis: "TEST" },
    { Kennzahl: "Ausgaben / Rashodi", Wert: k.expenses, Hinweis: "TEST" },
    { Kennzahl: "Ergebnis / Rezultat", Wert: k.result, Hinweis: "TEST" },
    { Kennzahl: "Break-even", Wert: k.breakEven, Hinweis: "TEST" },
    { Kennzahl: "ROI %", Wert: Number(k.roi.toFixed(2)), Hinweis: "TEST" }
  ];
  const filename = "EO-Werkstatt-Office-TEST-2026-11.xlsx";

  if (window.XLSX) {
    const book = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(kpiRows), "Kennzahlen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.orders), "Bestellungen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.returns), "Rueckgaben-Storno");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.movements), "Eingang-Ausgang");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.suppliers), "Lieferanten");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.invoices), "Rechnungen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(DATA.costs), "Betriebskosten");
    XLSX.writeFile(book, filename);
  } else {
    const lines = ["Kennzahl;Wert;Hinweis"];
    kpiRows.forEach((row) => lines.push(`${row.Kennzahl};${String(row.Wert).replace(".", ",")};TEST`));
    const blob = new Blob(["\uFEFF" + lines.join("\n")], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "EO-Werkstatt-Office-TEST-2026-11.csv";
    link.click();
    URL.revokeObjectURL(url);
  }

  const button = document.getElementById("export-btn");
  const previous = button.innerHTML;
  button.innerHTML = `<span>${t("exportDone")}</span><span class="arrow">✓</span>`;
  setTimeout(() => {
    button.innerHTML = previous;
  }, 1800);
}

function initUpload() {
  const zone = document.getElementById("upload-zone");
  const input = document.getElementById("upload-input");
  const previews = document.getElementById("previews");
  const objectUrls = [];

  function addFiles(files) {
    Array.from(files || []).forEach((file) => {
      if (!file.type.startsWith("image/")) return;
      const url = URL.createObjectURL(file);
      objectUrls.push(url);
      const figure = document.createElement("figure");
      figure.innerHTML = `<img src="${url}" alt="${file.name}"><figcaption>TEST · ${file.name}</figcaption>`;
      previews.appendChild(figure);
    });
  }

  zone.addEventListener("click", () => input.click());
  zone.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      input.click();
    }
  });
  input.addEventListener("change", () => addFiles(input.files));
  ["dragenter", "dragover"].forEach((name) => {
    zone.addEventListener(name, (event) => {
      event.preventDefault();
      zone.style.background = "rgba(244, 207, 72, 0.22)";
    });
  });
  ["dragleave", "drop"].forEach((name) => {
    zone.addEventListener(name, (event) => {
      event.preventDefault();
      zone.style.background = "";
    });
  });
  zone.addEventListener("drop", (event) => addFiles(event.dataTransfer.files));
}

function setLang(lang) {
  state.lang = lang === "bs" ? "bs" : "de";
  try {
    localStorage.setItem("eo-office-lang", state.lang);
  } catch (err) {
    /* ignore */
  }
  render();
}

function init() {
  try {
    const saved = localStorage.getItem("eo-office-lang");
    if (saved === "bs" || saved === "de") state.lang = saved;
  } catch (err) {
    /* ignore */
  }

  document.querySelectorAll(".lang-switch button").forEach((button) => {
    button.addEventListener("click", () => setLang(button.dataset.lang));
  });
  document.getElementById("export-btn").addEventListener("click", exportExcel);
  initUpload();
  render();

  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.register("./sw.js").catch(() => {
      /* raw.githack or file protocol may block SW; manifest still works when hosted */
    });
  }
}

document.addEventListener("DOMContentLoaded", init);

const DB_NAME = "eo-werkstatt-office";
const DB_VERSION = 1;
const STORES = ["invoices", "orders", "returns", "movements", "suppliers"];

const state = {
  lang: "de",
  month: "all",
  db: null,
  data: { invoices: [], orders: [], returns: [], movements: [], suppliers: [] },
  editing: null,
  pendingImage: null
};

function t(key) {
  return (I18N[state.lang] && I18N[state.lang][key]) || I18N.de[key] || key;
}

function money(value) {
  return new Intl.NumberFormat("de-DE", { style: "currency", currency: "EUR" }).format(Number(value) || 0);
}

function shortDate(iso) {
  if (!iso) return "";
  const [y, m, d] = iso.split("-");
  return `${d}.${m}.${y}`;
}

function todayIso() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function monthKey(iso) {
  return iso ? String(iso).slice(0, 7) : "";
}

function uid() {
  if (crypto.randomUUID) return crypto.randomUUID();
  return `id-${Date.now()}-${Math.random().toString(16).slice(2)}`;
}

function invoiceValue(row) {
  const gross = Number(row.gross);
  const net = Number(row.net);
  if (!Number.isNaN(gross) && row.gross !== "" && row.gross != null) return gross;
  if (!Number.isNaN(net) && row.net !== "" && row.net != null) return net;
  return 0;
}

function inMonth(iso, month) {
  if (!month || month === "all") return true;
  return monthKey(iso) === month;
}

function active(rows, month, dateField) {
  return rows.filter((row) => !row.storno && inMonth(row[dateField] || row.date, month));
}

function openDb() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(DB_NAME, DB_VERSION);
    req.onupgradeneeded = () => {
      const db = req.result;
      STORES.forEach((name) => {
        if (!db.objectStoreNames.contains(name)) db.createObjectStore(name, { keyPath: "id" });
      });
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

function txDone(tx) {
  return new Promise((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error);
    tx.onabort = () => reject(tx.error);
  });
}

async function loadAll() {
  const data = { invoices: [], orders: [], returns: [], movements: [], suppliers: [] };
  await Promise.all(
    STORES.map(
      (name) =>
        new Promise((resolve, reject) => {
          const tx = state.db.transaction(name, "readonly");
          const req = tx.objectStore(name).getAll();
          req.onsuccess = () => {
            data[name] = req.result || [];
            resolve();
          };
          req.onerror = () => reject(req.error);
        })
    )
  );
  const sortDate = (a, b) => String(b.date || "").localeCompare(String(a.date || ""));
  data.invoices.sort(sortDate);
  data.orders.sort(sortDate);
  data.returns.sort(sortDate);
  data.movements.sort(sortDate);
  data.suppliers.sort((a, b) => String(a.name || "").localeCompare(String(b.name || ""), "de"));
  state.data = data;
}

async function putRecord(store, record) {
  const tx = state.db.transaction(store, "readwrite");
  tx.objectStore(store).put(record);
  await txDone(tx);
}

async function rememberSupplier(name, extra) {
  const trimmed = (name || "").trim();
  if (!trimmed) return;
  const existing = state.data.suppliers.find((row) => row.name.toLowerCase() === trimmed.toLowerCase());
  if (existing) return;
  const row = { id: uid(), name: trimmed, city: "", contact: "", note: "", created: todayIso(), ...(extra || {}) };
  await putRecord("suppliers", row);
}

function kpis(month) {
  const invoices = active(state.data.invoices, month, "date");
  const revenue = invoices.filter((row) => row.kind === "out").reduce((sum, row) => sum + invoiceValue(row), 0);
  const expenses = invoices.filter((row) => row.kind === "in").reduce((sum, row) => sum + invoiceValue(row), 0);
  const returnsSum = active(state.data.returns, month, "date").reduce((sum, row) => sum + Number(row.amount || 0), 0);
  const netExpenses = expenses + returnsSum;
  const result = revenue - netExpenses;
  const breakEven = netExpenses;
  const roi = expenses === 0 ? 0 : (result / expenses) * 100;
  const coverage = breakEven === 0 ? 0 : (revenue / Math.max(breakEven, 0.0001)) * 100;
  return { revenue, expenses, returnsSum, netExpenses, result, breakEven, roi, coverage };
}

function supplierStats(name, month) {
  const invoices = active(state.data.invoices, month, "date").filter(
    (row) => row.kind === "in" && (row.partner || "").toLowerCase() === name.toLowerCase()
  );
  const spentInv = invoices.reduce((sum, row) => sum + invoiceValue(row), 0);
  const spentOrd = active(state.data.orders, month, "date")
    .filter((row) => (row.supplier || "").toLowerCase() === name.toLowerCase())
    .reduce((sum, row) => sum + Number(row.qty || 0) * Number(row.price || 0), 0);
  const returned = active(state.data.returns, month, "date")
    .filter((row) => {
      const order = state.data.orders.find((item) => item.id === row.orderId);
      const supplier = order ? order.supplier : row.supplier;
      return (supplier || "").toLowerCase() === name.toLowerCase();
    })
    .reduce((sum, row) => sum + Number(row.amount || 0), 0);
  return { spent: spentInv || spentOrd, returned };
}

function applyI18n() {
  document.documentElement.lang = state.lang === "bs" ? "bs" : "de";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18n);
  });
  document.querySelectorAll(".lang-switch button").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === state.lang));
  });
}

function fillMonthFilter() {
  const select = document.getElementById("month-filter");
  const keys = new Set();
  STORES.forEach((name) => {
    state.data[name].forEach((row) => {
      if (row.date) keys.add(monthKey(row.date));
    });
  });
  const current = monthKey(todayIso());
  keys.add(current);
  const months = Array.from(keys).filter(Boolean).sort().reverse();
  const previous = state.month;
  select.innerHTML =
    `<option value="all">${t("monthAll")}</option>` +
    months
      .map((key) => {
        const [y, m] = key.split("-");
        const label = `${m}.${y}`;
        return `<option value="${key}">${label}</option>`;
      })
      .join("");
  if (previous && (previous === "all" || months.includes(previous))) select.value = previous;
  else select.value = "all";
  state.month = select.value;
}

function amountCell(value) {
  const cls = value < 0 ? "amount-neg" : "amount-pos";
  return `<td class="num ${cls}">${money(value)}</td>`;
}

function stornoTag(row) {
  return row.storno ? ` <span class="tag tag-storno">${t("storno")}</span>` : "";
}

function emptyBox(message, open) {
  return `<div class="empty-state"><p>${message}</p><button class="btn btn-yellow btn-small" type="button" data-open="${open}">${t(
    { invoice: "addInvoice", order: "addOrder", return: "addReturn", movement: "addMovement", supplier: "addSupplier" }[open]
  )}</button></div>`;
}

function tableWrap(head, body) {
  return `<div class="table-wrap"><table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>`;
}

function renderKpis() {
  const k = kpis(state.month);
  document.getElementById("kpi-revenue").textContent = money(k.revenue);
  document.getElementById("kpi-expenses").textContent = money(k.expenses);
  const retEl = document.getElementById("kpi-returns");
  retEl.textContent = money(k.returnsSum);
  retEl.classList.toggle("neg", k.returnsSum < 0);
  const resultEl = document.getElementById("kpi-result");
  resultEl.textContent = money(k.result);
  resultEl.classList.toggle("neg", k.result < 0);
  document.getElementById("kpi-break").textContent = money(Math.max(k.breakEven, 0));
  const breakSub = document.getElementById("kpi-break-sub");
  if (k.expenses === 0 && k.returnsSum === 0) {
    breakSub.textContent = t("breakEmpty");
    document.getElementById("break-bar").style.width = "0%";
  } else {
    const delta = k.revenue - k.breakEven;
    breakSub.textContent = `${money(Math.abs(delta))} ${delta >= 0 ? t("breakOver") : t("breakUnder")}`;
    document.getElementById("break-bar").style.width = `${Math.min(Math.max(k.coverage, 0), 100)}%`;
  }
  document.getElementById("kpi-roi").textContent = k.expenses === 0 ? "—" : `${k.roi.toFixed(1).replace(".", ",")}%`;
}

function renderInvoices() {
  const rows = state.data.invoices.filter((row) => inMonth(row.date, state.month));
  const root = document.getElementById("invoices-view");
  if (!rows.length) {
    root.innerHTML = emptyBox(t("emptyInvoices"), "invoice");
    return;
  }
  root.innerHTML = tableWrap(
    `<th>${t("colDate")}</th><th>${t("colNr")}</th><th>${t("colType")}</th><th>${t("colPartner")}</th><th class="num">${t("colAmount")}</th><th>${t("colStatus")}</th>`,
    rows
      .map((row) => {
        const kind = row.kind === "out" ? t("invOut") : t("invIn");
        const paid = row.paid ? t("paid") : t("unpaid");
        return `<tr class="clickable${row.storno ? " row-neg" : ""}" data-edit="invoice" data-id="${row.id}">
          <td>${shortDate(row.date)}</td>
          <td>${row.number || "—"}${stornoTag(row)}</td>
          <td><span class="tag ${row.kind === "out" ? "tag-out" : "tag-in"}">${kind}</span></td>
          <td>${row.partner || "—"}<div class="muted">${row.description || ""}</div></td>
          ${amountCell(invoiceValue(row))}
          <td class="status">${row.storno ? t("storno") : paid}</td>
        </tr>`;
      })
      .join("")
  );
}


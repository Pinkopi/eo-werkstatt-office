function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

function exportJson() {
  const payload = {
    app: "eo-werkstatt-office",
    version: 1,
    exported: new Date().toISOString(),
    data: state.data
  };
  const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
  downloadBlob(`eo-werkstatt-office-sicherung-${todayIso()}.json`, blob);
  flashButton(document.getElementById("export-json"), "exportDone");
}

async function importJsonFile(file) {
  try {
    const text = await file.text();
    const payload = JSON.parse(text);
    const incoming = payload.data || payload;
    if (!incoming || typeof incoming !== "object") throw new Error("shape");
    if (!confirm(t("importConfirm"))) return;
    const tx = state.db.transaction(STORES, "readwrite");
    STORES.forEach((name) => {
      const store = tx.objectStore(name);
      store.clear();
      (incoming[name] || []).forEach((row) => {
        if (row && row.id) store.put(row);
      });
    });
    await txDone(tx);
    await loadAll();
    render();
    flashButton(document.getElementById("import-json-btn"), "importOk");
  } catch (err) {
    alert(t("importFail"));
  }
}

function exportExcel() {
  const k = kpis(state.month);
  const kpiRows = [
    { Feld: "Umsatz / Promet", Wert: k.revenue },
    { Feld: "Ausgaben / Rashodi", Wert: k.expenses },
    { Feld: "Rückgaben / Povrati", Wert: k.returnsSum },
    { Feld: "Ergebnis / Rezultat", Wert: k.result },
    { Feld: "Break-even", Wert: k.breakEven },
    { Feld: "ROI %", Wert: Number(k.roi.toFixed(2)) },
    { Feld: "Monat", Wert: state.month }
  ];
  const invoices = state.data.invoices.map((row) => ({
    id: row.id,
    art: row.kind,
    datum: row.date,
    nummer: row.number,
    partner: row.partner,
    netto: row.net,
    brutto: row.gross,
    beschreibung: row.description,
    bezahlt: row.paid ? "ja" : "nein",
    storno: row.storno ? "ja" : "nein"
  }));
  const filename = `eo-werkstatt-office-${todayIso()}.xlsx`;
  if (window.XLSX) {
    const book = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(kpiRows), "Kennzahlen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(invoices), "Rechnungen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(state.data.orders), "Bestellungen");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(state.data.returns), "Rueckgaben");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(state.data.movements), "Eingang-Ausgang");
    XLSX.utils.book_append_sheet(book, XLSX.utils.json_to_sheet(state.data.suppliers), "Lieferanten");
    XLSX.writeFile(book, filename);
  } else {
    const lines = ["Feld;Wert"].concat(kpiRows.map((row) => `${row.Feld};${row.Wert}`));
    downloadBlob(`eo-werkstatt-office-${todayIso()}.csv`, new Blob(["\uFEFF" + lines.join("\n")], { type: "text/csv;charset=utf-8;" }));
  }
  flashButton(document.getElementById("export-xlsx"), "exportDone");
}

